    entity_id text NOT NULL,
    catalog_version_from integer NOT NULL,
    content_hash text NOT NULL,
    data jsonb NOT NULL,
    PRIMARY KEY (entity_id, catalog_version_from)
);

CREATE TABLE catalog.load (
    catalog_version integer NOT NULL,
    commit text NOT NULL,
    loaded_at timestamptz NOT NULL,
    environment text NOT NULL,
    PRIMARY KEY (catalog_version, environment),
    CONSTRAINT load_environment_chk CHECK (environment IN ('staging', 'prod'))
);

CREATE TABLE catalog.core_call (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL,
    catalog_version integer NOT NULL,
    payload jsonb NOT NULL,
    CONSTRAINT core_call_kind_chk CHECK (kind IN ('version', 'recheck'))
);

